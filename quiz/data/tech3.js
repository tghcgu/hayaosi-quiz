function parse(text) {
  return text.trim().split('\n').map((l) => l.split('|').map((s) => s.trim()));
}

export default {
  genre: '乗り物・テクノロジー',
  build() {
    const out = [];
    const codes = parse(CAR_CODES);
    for (const [code, meaning] of codes) out.push(makeQ(`JRの車両の記号で、「${code}」が表すのは？`, meaning, codes.map(([, m]) => m)));
    const plates = parse(PLATES);
    for (const [look, kind] of plates) {
      out.push(makeQ(`「${look}」のナンバープレートの車は？`, kind, plates.map(([, k]) => k)));
      out.push(makeQ(`${kind}のナンバープレートの色は？`, look, plates.map(([l]) => l)));
    }
    for (const [q, answer, wrong] of FACTS) out.push({ q, answer, wrong });
    return out;
  },
};
