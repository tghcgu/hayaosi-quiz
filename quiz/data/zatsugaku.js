function parse(text) {
  return text.trim().split('\n').map((l) => l.split('|').map((s) => s.trim()));
}

export default {
  genre: '雑学',
  build() {
    const out = [];
    const days = parse(DAYS);
    for (const [date, name] of days) {
      out.push(makeQ(`${date}は何の日？`, name, days.map(([, n]) => n)));
      out.push(makeQ(`「${name}」は何月何日？`, date, days.map(([d]) => d)));
    }
    const origins = parse(ORIGINS);
    const langs = [...new Set(origins.map(([, l]) => l)), '英語', 'スペイン語'];
    for (const [word, lang] of origins) out.push(makeQ(pickOne([`「${word}」という言葉は、もともと何語から来た？`, `外来語「${word}」のもとになった言語は？`], word), lang, langs));
    const full = parse(FULL);
    for (const [short, long] of full) {
      out.push(makeQ(`「${short}」を略さずに言うと？`, long, full.map(([, l]) => l)));
      // 「コンビニエンスストア→コンビニ」のように、短い言い方がそのまま入っているものは出さない
      if (!long.includes(short)) out.push(makeQ(`「${long}」を短くした言い方は？`, short, full.map(([s]) => s)));
    }
    const parts = parse(PARTS);
    for (const [desc, name] of parts) {
      out.push(makeQ(`「${desc}」の名前は？`, name, parts.map(([, n]) => n)));
      out.push(makeQ(`「${name}」とは、何の部分や部品？`, desc, parts.map(([d]) => d)));
    }
    const marks = parse(MARKS);
    for (const [look, meaning] of marks) out.push(makeQ(`${look}は、何を表す？`, meaning, marks.map(([, m]) => m)));
    const counters = parse(COUNTERS);
    for (const [thing, unit] of counters) out.push(makeQ(`${thing}を数えるときの単位は？`, unit, counters.map(([, u]) => u)));
    for (const [q, answer, wrong] of [...SANDAI, ...FACTS]) out.push({ q, answer, wrong });
    return out;
  },
};
