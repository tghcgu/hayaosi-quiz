function parse(text) {
  return text.trim().split('\n').map((l) => l.split('|').map((s) => s.trim()));
}

export default {
  genre: '雑学',
  build() {
    const out = [];
    for (const [table, word] of [[THANKS, 'ありがとう'], [HELLO, 'こんにちは']]) {
      const rows = parse(table);
      for (const [lang, phrase] of rows) {
        out.push(makeQ(`${lang}で「${word}」は？`, phrase, rows.map(([, p]) => p)));
        out.push(makeQ(`「${phrase}」は、何語で「${word}」という意味？`, lang, rows.map(([l]) => l)));
      }
    }
    for (const [q, answer, wrong] of FACTS) out.push({ q, answer, wrong });
    return out;
  },
};
