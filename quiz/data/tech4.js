    both(out, AIRPORTS, (a) => `${a}の空港コードは？`, (c) => `空港コード「${c}」の空港は？`);
    both(out, MAKERS, (m) => `自動車メーカー「${m}」はどこの国のメーカー？`, null, ['日本', 'ドイツ', 'フランス']);
