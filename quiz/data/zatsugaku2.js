function parse(text) {
  return text.trim().split('\n').map((l) => l.split('|').map((s) => s.trim()));
}

export default {
  genre: '雑学',
  build() {
    const out = [];
    const symbols = parse(SYMBOLS);
    for (const [sym, name] of symbols) {
      out.push(makeQ(`記号「${sym}」の名前は？`, name, symbols.map(([, n]) => n)));
      out.push(makeQ(`「${name}」とよばれる記号は？`, sym, symbols.map(([s]) => s)));
    }
    const units = parse(UNITS);
    for (const [unit, size] of units) out.push(makeQ(`${unit}は、およそどれくらい？`, size, units.map(([, s]) => s)));
    for (const [q, answer, wrong] of FACTS) out.push({ q, answer, wrong });
    return out;
  },
};
