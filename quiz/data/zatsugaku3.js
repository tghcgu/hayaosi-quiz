function parse(text) {
  return text.trim().split('\n').map((l) => l.split('|').map((s) => s.trim()));
}

export default {
  genre: '雑学',
  build() {
    const out = [];
    for (const [bird, pref] of parse(PREF_BIRDS)) out.push({ q: `「${bird}」を県の鳥（都道府県の鳥）にしている都道府県は？`, answer: pref, wrong: prefWrong(pref, bird) });
    const fathers = parse(FATHERS);
    for (const [title, person] of fathers) out.push(makeQ(`「${title}」とよばれる人物は？`, person, fathers.map(([, p]) => p)));
    const calling = parse(CALLING);
    for (const [country, code] of calling) {
      out.push(makeQ(`${country}の国際電話の国番号は？`, code, calling.map(([, c]) => c)));
      out.push(makeQ(`国際電話の国番号「${code}」の国は？`, country, calling.map(([c]) => c)));
    }
    const currency = parse(CURRENCY);
    for (const [sym, name] of currency) {
      out.push(makeQ(`通貨の記号「${sym}」が表す通貨は？`, name, currency.map(([, n]) => n)));
      out.push(makeQ(`通貨「${name}」を表す記号は？`, sym, currency.map(([s]) => s)));
    }
    const sounds = parse(SOUNDS);
    for (const [animal, sound] of sounds) {
      out.push(makeQ(`英語で、${animal}の鳴き声はどう表す？`, sound, sounds.map(([, s]) => s)));
      out.push(makeQ(`英語で「${sound}」と鳴く動物は？`, animal, sounds.map(([a]) => a)));
    }
    const aliases = parse(ALIASES);
    for (const [thing, alias] of aliases) out.push(makeQ(`「${thing}」の昔からの別名は？`, alias, aliases.map(([, a]) => a)));
    const daiji = parse(DAIJI);
    for (const [n, k] of daiji) out.push(makeQ(`お札などに使われる漢数字の「大字」で、${n}はどう書く？`, k, daiji.map(([, x]) => x).concat(['肆', '伍'])));
    const dirs = parse(DIRECTIONS);
    for (const [eto, dir] of dirs) out.push(makeQ(`十二支で方角を表すとき、「${eto}」はどの方角？`, dir, ['北', '南', '東', '西']));
    const numbers = ['一', '二', '三', '四', '五', '七', '八', '九', '十', '百', '千'];
    for (const [phrase, n] of parse(NUMBER_WORDS)) out.push(makeQ(`「${phrase}」の□に入る数字は？`, n, numbers));
    for (const [q, answer, wrong] of FACTS) out.push({ q, answer, wrong });
    return out;
  },
};
