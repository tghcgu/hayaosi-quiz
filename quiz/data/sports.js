function parse(text) {
  return text.trim().split('\n').map((l) => l.split('|').map((s) => s.trim()));
}

export default {
  genre: 'スポーツ',
  build() {
    const out = [];

    for (const [sport, n] of parse(TEAM_SIZE)) {
      const num = Number(n);
      const wrong = [num + 1, num - 1, num + 2, num - 2, num + 4].filter((x) => x > 0 && x !== num).slice(0, 3).map((x) => `${x}人`);
      out.push({ q: `${sport}は、1チーム何人で試合をする？（コートやフィールドに出る人数）`, answer: `${num}人`, wrong });
    }

    const origins = parse(ORIGINS);
    const countries = [...new Set(origins.map(([, c]) => c)), 'フランス', 'ドイツ', 'オーストラリア', 'ブラジル', '中国'];
    for (const [sport, country] of origins) out.push(makeQ(`${sport}が生まれた国は？`, country, countries));

    const olympics = parse(OLYMPICS).map(([y, city, season]) => ({ year: Number(y), city, season }));
    for (const o of olympics) {
      const same = olympics.filter((x) => x.season === o.season);
      const label = o.season === '夏' ? '夏季' : '冬季';
      const when = o.year >= 2028 ? '開かれる予定の' : o.year === 2020 ? '（2021年に）開かれた' : '開かれた';
      out.push(makeQ(`${o.year}年の${label}オリンピックが${when}都市は？`, o.city, same.map((x) => x.city)));
      // 何度も開いた都市は「何年？」の答えが1つに決まらないので、1回だけの都市にする
      if (same.filter((x) => x.city === o.city).length === 1 && o.year <= 2024) {
        const years = same.map((x) => `${x.year}年`);
        out.push(makeQ(`${o.city}で${label}オリンピックが開かれたのは何年？`, `${o.year}年`, years.filter((y) => Math.abs(Number.parseInt(y, 10) - o.year) <= 20)) ?? makeQ(`${o.city}で${label}オリンピックが開かれたのは何年？`, `${o.year}年`, years));
      }
    }

    const terms = parse(TERMS);
    const sports = [...new Set(terms.map(([, s]) => s))];
    for (const [term, sport] of terms) {
      out.push(makeQ(pickOne([`「${term}」という用語が使われる競技は？`, `「${term}」は、何という競技の用語？`], term), sport, sports));
    }

    const athletes = parse(ATHLETES);
    const athleteSports = [...new Set(athletes.map(([, s]) => s))];
    for (const [name, sport, deed] of athletes) {
      out.push(makeQ(`${name}は、何の競技の選手？`, sport, athleteSports));
      const sameSport = athletes.filter(([, s]) => s === sport).map(([n]) => n);
      const pool = sameSport.length >= 4 ? sameSport : athletes.map(([n]) => n);
      out.push(makeQ(`${deed}選手は？`, name, pool));
    }

    const npb = parse(NPB);
    const prefs = [...new Set(npb.map(([, , p]) => p)), '静岡県', '京都府'];
    for (const [team, league, pref] of npb) {
      out.push(makeQ(`プロ野球の${team}が所属するリーグは？`, league, ['セ・リーグ', 'パ・リーグ', 'イースタン・リーグ', 'ウエスタン・リーグ']));
      // 球団名に都道府県名が入っているもの（千葉ロッテなど）は、答えが見えてしまうので出さない
      if (!team.includes(pref.replace(/[都府県]$/, ''))) out.push(makeQ(`プロ野球の${team}が本拠地をおく都道府県は？`, pref, prefs));
    }

    for (const [q, answer, wrong] of FACTS) out.push({ q, answer, wrong });
    return out;
  },
};
