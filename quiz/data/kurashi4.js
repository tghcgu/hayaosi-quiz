function parse(text) {
  return text.trim().split('\n').map((l) => l.split('|').map((s) => s.trim()));
}

export default {
  genre: '暮らし',
  build() {
    const out = [];
    const family = parse(FAMILY);
    for (const [rel, name] of family) {
      out.push(makeQ(`自分から見て「${rel}」のことを何という？`, name, family.map(([, n]) => n)));
      out.push(makeQ(`「${name}」とは、自分から見てどんな関係の人？`, rel, family.map(([r]) => r)));
    }
    for (let year = 2020; year <= 2031; year++) {
      out.push(makeQ(`${year}年の干支は？`, ETO[(year - 2020) % 12], ETO));
    }
    for (const [era, year] of ERA_YEARS) {
      out.push({ q: `${era}は、西暦何年？`, answer: `${year}年`, wrong: [year + 1, year - 1, year + 10].map((y) => `${y}年`) });
    }
    for (const [q, answer, wrong] of FACTS) out.push({ q, answer, wrong });
    return out;
  },
};
