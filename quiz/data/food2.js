function parse(text) {
  return text.trim().split('\n').map((l) => l.split('|').map((s) => s.trim()));
}

export default {
  genre: '食べ物・飲み物',
  build() {
    const out = [];
    for (const [food, season] of parse(SEASON)) out.push(makeQ(`${food}の旬（いちばんおいしい季節）は？`, season, ['春', '夏', '秋', '冬']));
    for (const [table, label] of [[PREP, '料理の下ごしらえ'], [TOOLS, '台所の道具'], [DRINKS, '飲み物']]) {
      const rows = parse(table);
      for (const [name, desc] of rows) {
        out.push(makeQ(`${label}で、「${desc}」を何という？`, name, rows.map(([n]) => n)));
        out.push(makeQ(`「${name}」とは何のこと？`, desc, rows.map(([, d]) => d)));
      }
    }
    for (const [food, pref] of parse(LOCAL)) out.push({ q: `郷土料理「${food}」で知られる都道府県は？`, answer: pref, wrong: prefWrong(pref, food) });
    for (const [q, answer, wrong] of FACTS) out.push({ q, answer, wrong });
    return out;
  },
};
