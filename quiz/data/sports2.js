function parse(text) {
  return text.trim().split('\n').map((l) => l.split('|').map((s) => s.trim()));
}

export default {
  genre: 'スポーツ',
  build() {
    const out = [];
    const times = parse(MATCH_TIME);
    for (const [sport, time] of times) out.push(makeQ(`${sport}の試合時間は？`, time, times.map(([, t]) => t)));

    const places = parse(PLACES);
    const placeSports = [...new Set(places.map(([, s]) => s))];
    for (const [place, sport] of places) out.push(makeQ(`「${place}」が使われる競技は？`, sport, placeSports));

    const meanings = parse(MEANINGS);
    for (const [term, meaning, sport] of meanings) {
      out.push(makeQ(`${sport}の用語「${term}」の意味は？`, meaning, meanings.map(([, m]) => m)));
      out.push(makeQ(`${sport}で「${meaning}」を何という？`, term, meanings.filter(([, , s]) => s === sport).map(([t]) => t).concat(meanings.map(([t]) => t))));
    }

    const athletes = parse(ATHLETES);
    const sports = [...new Set(athletes.map(([, s]) => s)), '陸上競技', 'テニス'];
    for (const [name, sport, deed] of athletes) {
      out.push(makeQ(`${name}は、何の競技の選手？`, sport, sports));
      out.push(makeQ(`${deed}のは誰？`, name, athletes.map(([n]) => n)));
    }

    for (const [q, answer, wrong] of FACTS) out.push({ q, answer, wrong });
    return out;
  },
};
