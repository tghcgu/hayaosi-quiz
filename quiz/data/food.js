function parse(text) {
  return text.trim().split('\n').map((l) => l.split('|').map((s) => s.trim()));
}

function pairs(out, text, qText, extraPool = []) {
  const rows = parse(text);
  const answers = [...rows.map(([, a]) => a), ...extraPool];
  for (const [a, b] of rows) out.push(makeQ(qText(a), b, answers));
  return rows;
}

