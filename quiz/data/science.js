function parse(text) {
  return text.trim().split('\n').map((l) => l.split('|').map((s) => s.trim()));
}

export default {
  genre: '理数系',
  build() {
    const out = [];

    const elements = parse(ELEMENTS).map(([n, sym, name]) => ({ n: Number(n), sym, name }));
    const names = elements.map((e) => e.name);
    const symbols = elements.map((e) => e.sym);
    for (const e of elements) {
      out.push(makeQ(pickOne([`元素記号「${e.sym}」で表される元素は？`, `「${e.sym}」はどの元素の記号？`], e.sym), e.name, names));
      out.push(makeQ(`「${e.name}」の元素記号は？`, e.sym, symbols, { filter: (s) => s[0] === e.sym[0] })
        ?? makeQ(`「${e.name}」の元素記号は？`, e.sym, symbols));
      const near = elements.filter((x) => x !== e && Math.abs(x.n - e.n) <= 6).map((x) => x.name);
      out.push(makeQ(`原子番号${e.n}の元素は？`, e.name, near.length >= 3 ? near : names));
    }

    const formulas = parse(FORMULAS);
    for (const [name, f] of formulas) {
      out.push(makeQ(`「${name}」の化学式は？`, f, formulas.map(([, x]) => x)));
      out.push(makeQ(`化学式「${f}」で表される物質は？`, name, formulas.map(([n]) => n)));
    }

    const units = parse(UNITS);
    for (const [q, u] of units) {
      out.push(makeQ(`${q}を表す単位は？`, u, units.map(([, x]) => x)));
      out.push(makeQ(`「${u}」は何を表す単位？`, q, units.map(([x]) => x)));
    }

    const scientists = parse(SCIENTISTS);
    for (const [person, work] of scientists) {
      out.push(makeQ(`${person}の業績として知られるのは？`, work, scientists.map(([, w]) => w)));
      out.push(makeQ(pickOne([`「${work}」で知られる人物は？`, `「${work}」をなしとげた人物は？`], work), person, scientists.map(([p]) => p)));
    }

    for (const [animal, cls] of parse(ANIMAL_CLASS)) {
      const pool = VERTEBRATES.includes(cls) ? VERTEBRATES : INVERTEBRATES;
      out.push({ ...makeQ(`${animal}は、生き物の分類で何のなかま？`, cls, pool), genre: '生き物・自然' });
    }

    for (let i = 0; i < PLANETS.length; i++) {
      out.push(makeQ(`太陽系で、太陽から${i + 1}番目に近い惑星は？`, PLANETS[i], PLANETS));
      out.push(makeQ(`${PLANETS[i]}は、太陽から数えて何番目の惑星？`, `${i + 1}番目`, PLANETS.map((_, k) => `${k + 1}番目`)));
    }

    const flame = parse(FLAME);
    for (const [el, color] of flame) {
      out.push(makeQ(`炎色反応で、${el}の炎は何色？`, color, flame.map(([, c]) => c)));
      out.push(makeQ(`炎色反応で、炎が「${color}」色になる元素は？`, el, flame.map(([e]) => e)));
    }

    // 計算で答えが決まる問題
    const r = rng('理科の計算');
    const int = (a, b) => a + Math.floor(r() * (b - a + 1));
    for (let i = 0; i < 25; i++) {
      const R = int(2, 20) * 5, I = int(1, 6);
      out.push(makeQ(`抵抗${R}Ωの電熱線に${I}Aの電流が流れるとき、電圧は何V？`, `${R * I}V`, [`${R + I}V`, `${R * I * 2}V`, `${R * I + 10}V`, `${Math.round(R / I)}V`]));
    }
    for (let i = 0; i < 20; i++) {
      const R = int(2, 12) * 5, I = int(1, 4), V = R * I;
      out.push(makeQ(`${V}Vの電圧をかけると${I}Aの電流が流れる電熱線の抵抗は何Ω？`, `${R}Ω`, [`${V * I}Ω`, `${R * 2}Ω`, `${R + 5}Ω`, `${R - 5}Ω`]));
    }
    for (let t = 1; t <= 12; t++) {
      const d = 340 * t;
      out.push(makeQ(`雷が光ってから${t}秒後に音が聞こえた。音の速さを秒速340mとすると、雷までの距離は？`, `${d}m`, [`${d + 340}m`, `${Math.max(340, d - 340)}m`, `${34 * t}m`, `${d * 2}m`]));
    }
    for (let i = 0; i < 15; i++) {
      const v = int(2, 20) * 5, dens = [0.9, 1, 2.7, 7.9, 8.9, 11.3, 19.3][i % 7];
      const m = Math.round(v * dens * 10) / 10;
      out.push(makeQ(`体積${v}cm³で質量${m}gの物質の密度は何g/cm³？`, `${dens}g/cm³`, ['0.9g/cm³', '1g/cm³', '2.7g/cm³', '7.9g/cm³', '8.9g/cm³', '11.3g/cm³', '19.3g/cm³']));
    }

    // FACTS は ['#ジャンル'] の目印ごとにジャンルが変わる
    let genre = '理数系';
    for (const [q, answer, wrong] of FACTS) {
      if (q.startsWith('#')) genre = q.slice(1);
      else out.push({ q, answer, wrong, genre });
    }
    return out;
  },
};
