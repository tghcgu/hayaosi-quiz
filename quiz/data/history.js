function parse(text) {
  return text.trim().split('\n').map((l) => l.split('|').map((s) => s.trim()));
}

// まちがいの時代は、正解から2〜4つ離れた時代から選ぶ
// （となりの時代は、時代の変わり目に活躍した人や出来事だと正解とまぎらわしいので使わない）
function nearEras(era, seed) {
  const i = ERAS.indexOf(era);
  const near = ERAS.filter((e, k) => Math.abs(k - i) >= 2 && Math.abs(k - i) <= 4);
  const far = ERAS.filter((e, k) => Math.abs(k - i) > 4);
  const r = rng(seed);
  return [...shuffle(near, r), ...shuffle(far, r)].slice(0, 3);
}

function nearYears(year, seed) {
  const r = rng(seed);
  const cands = shuffle([1, 2, 3, 5, 10, -1, -2, -3, -5, -10], r).map((d) => year + d);
  return cands.slice(0, 3).map((y) => `${y}年`);
}

