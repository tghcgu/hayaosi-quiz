function parse(text) {
  return text.trim().split('\n').map((l) => l.split('|').map((s) => s.trim()));
}

function both(out, text, q1, q2) {
  const rows = parse(text);
  for (const [a, b] of rows) {
    if (q1) out.push(makeQ(q1(a), b, rows.map(([, x]) => x)));
    if (q2) out.push(makeQ(q2(b), a, rows.map(([x]) => x)));
  }
}

export default {
  genre: '乗り物・テクノロジー',
  build() {
    const out = [];
    both(out, PLANE, (p) => `飛行機の「${p}」のはたらきは？`, (w) => `次の説明に当てはまる飛行機の部分は？「${w}」`);
    both(out, RAIL, (t) => `鉄道のことば「${t}」とは？`, (m) => `鉄道で「${m}」を何という？`);
    for (const [q, answer, wrong] of FACTS) out.push({ q, answer, wrong });
    return out;
  },
};
