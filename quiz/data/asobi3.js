    both(out, BOARD, (g) => `「${g}」はどんな遊び？`, (d) => `次の説明に当てはまる遊びは？「${d}」`);
    both(out, GOLDFISH, (g) => `金魚の「${g}」の特徴は？`, (d) => `「${d}」は、どの品種？`);
    both(out, TOOLS, (t) => `DIYで使う「${t}」は、何をする道具？`, (u) => `DIYで「${u}」道具は？`);
    both(out, TETSU, (t) => `鉄道ファンの「${t}」は、何が好きな人？`, (d) => `鉄道ファンで、「${d}」が好きな人を何という？`);
