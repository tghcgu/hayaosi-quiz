function parse(text) {
  return text.trim().split('\n').map((l) => l.split('|').map((s) => s.trim()));
}

export default {
  genre: 'ことば・文学',
  build() {
    const out = [];

    for (const [group, text] of Object.entries(READINGS)) {
      const pairs = parse(text);
      const kanjis = pairs.map(([k]) => k);
      const yomis = pairs.map(([, y]) => y);
      for (const [kanji, yomi] of pairs) {
        if (group === '国名') {
          out.push(makeQ(`漢字で「${kanji}」と書く国は？`, yomi, yomis));
          out.push(makeQ(`「${yomi}」を漢字で書くと？（国名）`, kanji, kanjis));
          continue;
        }
        const q1 = pickOne([`「${kanji}」の読み方は？`, `漢字「${kanji}」は何と読む？`], kanji);
        out.push(makeQ(q1, yomi, yomis, { filter: similarLength(yomi) }) ?? makeQ(q1, yomi, yomis));
        const label = { 魚や貝: '魚や貝', 植物: '植物', 動物: '動物', ことば: 'ことば' }[group];
        out.push(makeQ(`「${yomi}」を漢字で書くと？（${label}）`, kanji, kanjis));
      }
    }

    const yoji = parse(YOJI);
    const yojiWords = yoji.map(([w]) => w);
    const yojiMeanings = yoji.map(([, m]) => m);
    const yojiChars = [...new Set(yojiWords.join(''))];
    for (const [word, meaning] of yoji) {
      out.push(makeQ(pickOne([`四字熟語「${word}」の意味は？`, `「${word}」とはどういう意味？`], word), meaning, yojiMeanings));
      out.push(makeQ(`「${meaning}」という意味の四字熟語は？`, word, yojiWords));
      const pos = pickOne([1, 3], word + '穴');
      const blank = word.slice(0, pos) + '□' + word.slice(pos + 1);
      out.push(makeQ(`四字熟語「${blank}」の□に入る漢字は？`, word[pos], yojiChars, {
        filter: (c) => !yojiWords.includes(word.slice(0, pos) + c + word.slice(pos + 1)),
      }));
    }

    const kotowaza = parse(KOTOWAZA).map(([raw, meaning]) => ({
      text: raw.replace(/[[\]]/g, ''),
      blank: raw.replace(/\[.+?\]/, '□'),
      key: raw.match(/\[(.+?)\]/)[1],
      meaning,
    }));
    const kotoMeanings = kotowaza.map((k) => k.meaning);
    const kotoKeys = kotowaza.map((k) => k.key);
    for (const k of kotowaza) {
      out.push(makeQ(pickOne([`ことわざ「${k.text}」の意味は？`, `「${k.text}」とはどういう意味？`], k.text), k.meaning, kotoMeanings));
      out.push(makeQ(`ことわざ「${k.blank}」の□に入る言葉は？`, k.key, kotoKeys, { filter: similarLength(k.key) }) ?? makeQ(`ことわざ「${k.blank}」の□に入る言葉は？`, k.key, kotoKeys));
      out.push(makeQ(`「${k.meaning}」という意味のことわざは？`, k.text, kotowaza.map((x) => x.text)));
    }

    const kanyoku = parse(KANYOKU);
    const kanyoMeanings = kanyoku.map(([, m]) => m);
    const parts = [...new Set(kanyoku.map(([, , p]) => p))];
    for (const [phrase, meaning, part] of kanyoku) {
      out.push(makeQ(`慣用句「${phrase}」の意味は？`, meaning, kanyoMeanings));
      const blank = phrase.replace(part, '□');
      out.push(makeQ(`「${blank}」は「${meaning}」という意味。□に入る体の部分は？`, part, parts));
    }

    const taigi = parse(TAIGIGO);
    const taigiWords = taigi.flat();
    for (const [a, b] of taigi) {
      out.push(makeQ(`「${a}」の対義語（反対の意味の言葉）は？`, b, taigiWords, { filter: (x) => x !== a }));
      out.push(makeQ(`「${b}」の対義語（反対の意味の言葉）は？`, a, taigiWords, { filter: (x) => x !== b }));
    }

    const bushu = parse(BUSHU);
    const bushuNames = bushu.map(([, n]) => n);
    for (const [kanji, name] of bushu) out.push(makeQ(`漢字「${kanji}」の部首名は？`, name, bushuNames));

    for (const [q, answer, wrong] of KEIGO) out.push({ q, answer, wrong });
    return out;
  },
};
