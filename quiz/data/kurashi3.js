function parse(text) {
  return text.trim().split('\n').map((l) => l.split('|').map((s) => s.trim()));
}

export default {
  genre: '暮らし',
  build() {
    const out = [];
    const signs = parse(SIGNS);
    for (const [look, meaning] of signs) out.push(makeQ(`道路標識で、「${look}」の標識の意味は？`, meaning, signs.map(([, m]) => m)));
    const tools = parse(TOOLS);
    for (const [name, desc] of tools) {
      out.push(makeQ(`「${desc}」を何という？`, name, tools.map(([n]) => n)));
      out.push(makeQ(`昔ながらの生活道具「${name}」とはどんなもの？`, desc, tools.map(([, d]) => d)));
    }
    for (const [q, answer, wrong] of FACTS) out.push({ q, answer, wrong });
    return out;
  },
};
