function parse(text) {
  return text.trim().split('\n').map((l) => l.split('|').map((s) => s.trim()));
}

export default {
  genre: '暮らし',
  build() {
    const out = [];
    const clothes = parse(CLOTHES);
    for (const [name, desc] of clothes) {
      out.push(makeQ(`「${desc}」を何という？`, name, clothes.map(([n]) => n)));
      out.push(makeQ(`「${name}」とはどんなもの？`, desc, clothes.map(([, d]) => d)));
    }
    const cosme = parse(COSME);
    for (const [item, where] of cosme) out.push(makeQ(`化粧品の「${item}」を使うところは？`, where, cosme.map(([, w]) => w)));
    const pay = parse(PAY);
    for (const [card, how] of pay) out.push(makeQ(`「${card}」のしはらいのしくみは？`, how, [...pay.map(([, h]) => h), '店員に現金をあずけて使う']));
    for (const [q, answer, wrong] of FACTS) out.push({ q, answer, wrong });
    return out;
  },
};
