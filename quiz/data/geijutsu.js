function parse(text) {
  return text.trim().split('\n').map((l) => l.split('|').map((s) => s.trim()));
}

// 作品⇔作者の問題（同じ作者の別の作品はまちがいに入れない）
function works(out, text, kind, workLabel) {
  const rows = parse(text);
  const authors = [...new Set(rows.map(([, a]) => a))];
  for (const [work, author] of rows) {
    out.push(makeQ(pickOne([`${workLabel}「${work}」の作者は？`, `「${work}」を${kind}のは誰？`], work), author, authors));
  }
  for (const author of authors) {
    const own = rows.filter(([, a]) => a === author).map(([w]) => w);
    const others = rows.filter(([, a]) => a !== author).map(([w]) => w);
    const r = rng(author + kind);
    const answer = own[Math.floor(r() * own.length)];
    out.push({ q: `${author}の作品は？`, answer, wrong: shuffle(others, r).slice(0, 3) });
  }
}

export default {
  genre: '芸術・伝統文化',
  build() {
    const out = [];
    works(out, PAINTINGS, 'えがいた', '絵画');
    works(out, MUSIC, '作曲した', '曲');
    const names = parse(COMPOSER_NAMES);
    for (const [c, n] of names) out.push(makeQ(`「${n}」とよばれる作曲家は？`, c, names.map(([x]) => x)));
    const terms = parse(TERMS);
    for (const [t, m] of terms) {
      out.push(makeQ(`音楽記号・用語の「${t}」の意味は？`, m, terms.map(([, x]) => x)));
      out.push(makeQ(`音楽で「${m}」を表す記号・用語は？`, t, terms.map(([x]) => x)));
    }
    for (const [inst, kind] of parse(INSTRUMENTS)) out.push(makeQ(`${inst}は、楽器の分類で何？`, kind, ['弦楽器', '木管楽器', '金管楽器', '打楽器', '鍵盤楽器']));
    return out;
  },
};
