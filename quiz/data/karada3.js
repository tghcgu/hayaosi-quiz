function parse(text) {
  return text.trim().split('\n').map((l) => l.split('|').map((s) => s.trim()));
}

function both(out, text, q1, q2) {
  const rows = parse(text);
  for (const [a, b] of rows) {
    if (q1) out.push(makeQ(q1(a), b, rows.map(([, x]) => x)));
    if (q2) out.push(makeQ(q2(b), a, rows.map(([x]) => x)));
  }
}

