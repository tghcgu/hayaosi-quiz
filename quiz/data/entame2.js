function parse(text) {
  return text.trim().split('\n').map((l) => l.split('|').map((s) => s.trim()));
}

export default {
  genre: 'エンタメ',
  build() {
    const out = [];
    const chars = parse(CHARACTERS);
    const titles = chars.map(([, t]) => t);
    for (const [c, t] of chars) out.push(makeQ(`「${c}」が登場する作品は？`, t, titles));
    const consoles = parse(CONSOLES);
    for (const [c, y] of consoles) out.push(makeQ(`ゲーム機「${c}」が日本で発売された年は？`, y, consoles.map(([, x]) => x)));
    const makers = parse(MAKERS);
    for (const [c, m] of makers) out.push(makeQ(`ゲーム機「${c}」を発売した会社は？`, m, [...makers.map(([, x]) => x), 'NEC']));
    for (const [q, answer, wrong] of FACTS) out.push({ q, answer, wrong });
    return out;
  },
};
