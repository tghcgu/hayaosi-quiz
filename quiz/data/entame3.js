function parse(text) {
  return text.trim().split('\n').map((l) => l.split('|').map((s) => s.trim()));
}

function works(out, text, label, verb) {
  const rows = parse(text);
  const authors = [...new Set(rows.map(([, a]) => a))];
  for (const [work, author] of rows) out.push(makeQ(pickOne([`${label}「${work}」の${verb}は？`, `「${work}」の${verb}は誰？`], work), author, authors));
  for (const author of authors) {
    const own = rows.filter(([, a]) => a === author).map(([w]) => w);
    const others = rows.filter(([, a]) => a !== author).map(([w]) => w);
    const r = rng(author + label);
    out.push({ q: `${author}の作品は？（${label}）`, answer: own[Math.floor(r() * own.length)], wrong: shuffle(others, r).slice(0, 3) });
  }
}

export default {
  genre: 'エンタメ',
  build() {
    const out = [];
    works(out, FILMS, '映画', '監督');
    works(out, MANGA, '漫画', '作者');
    const terms = parse(TERMS);
    for (const [t, m] of terms) {
      out.push(makeQ(`映画の用語「${t}」とは？`, m, terms.map(([, x]) => x)));
      out.push(makeQ(`映画で「${m}」を何という？`, t, terms.map(([x]) => x)));
    }
    for (const [q, answer, wrong] of FACTS) out.push({ q, answer, wrong });
    return out;
  },
};
