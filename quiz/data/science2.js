function parse(text) {
  return text.trim().split('\n').map((l) => l.split('|').map((s) => s.trim()));
}

export default {
  genre: '理数系',
  build() {
    const out = [];
    for (const [animal, diet] of parse(DIET)) out.push({ ...makeQ(`${animal}は、主に何を食べる動物？`, diet, ['草食', '肉食', '雑食', '昆虫食']), genre: '生き物・自然' });
    const habitat = parse(HABITAT);
    for (const [animal, place] of habitat) out.push({ ...makeQ(`${animal}が野生でくらしている地域は？`, place, habitat.map(([, p]) => p)), genre: '生き物・自然' });
    for (const [el, group] of parse(GROUPS)) out.push(makeQ(`${el}は、周期表で何のなかま？`, group, ['貴ガス', 'アルカリ金属', 'ハロゲン', 'アルカリ土類金属']));
    const clouds = parse(CLOUDS);
    for (const [name, nick] of clouds) {
      out.push(makeQ(`「${name}」は、ふつう何雲とよばれる？`, nick, clouds.map(([, n]) => n)));
      out.push(makeQ(`「${nick}」の正式な雲の名前は？`, name, clouds.map(([n]) => n)));
    }

    // 計算で答えが決まる問題
    const r = rng('理科の計算2');
    const int = (a, b) => a + Math.floor(r() * (b - a + 1));
    const seen = new Set();
    const once = (q) => (seen.has(q) ? false : (seen.add(q), true));
    for (let i = 0; i < 40; i++) {
      const V = [100, 12, 6, 3, 9, 200][i % 6], I = int(1, 10);
      const P = V * I;
      const q = `${V}Vの電圧で${I}Aの電流が流れるとき、電力は何W？`;
      if (once(q)) out.push(makeQ(q, `${P}W`, [`${Math.round((V + I) * 10) / 10}W`, `${Math.round(P * 2 * 10) / 10}W`, `${Math.round((V / I) * 10) / 10}W`, `${P + 10}W`]));
    }
    for (let i = 0; i < 30; i++) {
      const F = int(1, 20) * 10, d = int(1, 5);
      const q = `${F}Nの力で物体を力の向きに${d}m動かしたときの仕事は何J？`;
      if (once(q)) out.push(makeQ(q, `${F * d}J`, [`${F + d}J`, `${F * d * 2}J`, `${Math.round(F / d)}J`, `${F * d + 10}J`]));
    }
    for (let i = 0; i < 30; i++) {
      const A = [0.01, 0.02, 0.05, 0.1, 0.2, 0.5][i % 6], P = int(1, 20) * 100;
      const F = Math.round(P * A * 100) / 100;
      const q = `面積${A}m²の面に${F}Nの力が垂直にはたらくときの圧力は何Pa？`;
      if (once(q)) out.push(makeQ(q, `${P}Pa`, [`${P * 10}Pa`, `${Math.round(P / 10)}Pa`, `${P + 100}Pa`, `${P * 2}Pa`]));
    }

    for (const [q, answer, wrong, genre] of FACTS) out.push({ q, answer, wrong, genre });
    return out;
  },
};
